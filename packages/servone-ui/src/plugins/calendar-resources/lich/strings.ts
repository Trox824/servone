export function textOf (lang: Lang): (key: StringKey, params?: Record<string, string | number>) => string {
  return (key, params = {}) => {
    const template = lang === 'vi' ? vi[key] ?? en[key] : en[key]
    return template.replace(/\{(\w+)\}/g, (placeholder, name: string) => String(params[name] ?? placeholder))
  }
}

export function dayUnit (t: ReturnType<typeof textOf>, count: number): string {
  return t(Math.abs(count) === 1 ? 'DayUnit' : 'DaysUnit')
}

export function balanceText (t: ReturnType<typeof textOf>, count: number): string {
  const days = dayUnit(t, count)
  return count < 0 ? t('DaysOver', { count: -count, days }) : t('DaysLeft', { count, days })
}
