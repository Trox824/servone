export function copyFor (lang: Lang): (key: CopyKey, params?: Record<string, string>) => string {
  const table = lang === 'vi' ? vi : en
  return (key, params) => table[key].replace(/\{(\w+)\}/g, (whole, name: string) => params?.[name] ?? whole)
}
