function rewrite (messages: Messages, rules: Array<[RegExp, string]>): Messages {
  const apply = (text: string): string => rules.reduce((acc, [re, to]) => acc.replace(re, to), text)
  const out: Messages = {}
  for (const [kind, value] of Object.entries(messages)) {
    if (value !== null && typeof value === 'object') {
      const kindOut: Record<string, string> = {}
      for (const [key, text] of Object.entries(value)) kindOut[key] = typeof text === 'string' ? apply(text) : text
      out[kind] = kindOut
    } else {
      out[kind] = value
    }
  }
  return out
}

