type Messages = Record<string, string | Record<string, string>>

function rebrand (messages: Messages): Messages {
  const out: Messages = {}
  for (const [kind, value] of Object.entries(messages)) {
    if (typeof value === 'string') {
      out[kind] = value.replace(BRAND_RE, BRAND)
    } else if (value !== null && typeof value === 'object') {
      const kindOut: Record<string, string> = {}
      for (const [key, text] of Object.entries(value)) {
        kindOut[key] = typeof text === 'string' ? text.replace(BRAND_RE, BRAND) : text
      }
      out[kind] = kindOut
    } else {
      out[kind] = value
    }
  }
  return out
}

setTimeout(() => {
  const plugins = new Set<Plugin>([...brandPlugins, ...(Object.keys(overrides) as Plugin[])])
  for (const plugin of plugins) {
    const upstream = upstreamLoaders[plugin]
    if (upstream === undefined) continue
    const byLang = overrides[plugin] ?? {}
    const rebrandIt = brandPlugins.includes(plugin)
    addStringsLoader(plugin, async (lang: string) => {
      const raw = (await upstream(lang).catch(async () => await upstream('en'))) as Messages & { default?: Messages }
      const base: Messages = raw.default !== undefined ? raw.default : raw
      const rules = rewrites[plugin]?.[lang]
      const rebranded = rebrandIt ? rebrand(base) : base
      const branded = rules !== undefined ? rewrite(rebranded, rules) : rebranded
      const string = branded.string
      return {
        ...branded,
        string: { ...(typeof string === 'object' && string !== null ? string : {}), ...(byLang[lang] ?? {}) }
      } as unknown as Record<string, IntlString>
    })
  }
}, 0)
